async def test_endpoint_falls_back_to_the_octoprint_download(make_client, upstream):
    upstream.app[STORAGE]["my files/cube #1.gcode"] = (
        block("thumbnail", 12, 10, tiny_png(12, 10)) + "G28\n"
    ).encode()
