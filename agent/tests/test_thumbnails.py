@needs_samples
def test_qoi_is_decoded_pixel_perfect():
    thumb = extract_from_file(SAMPLES / "coaster_prusaslicer-qoi.gcode")
    rows = png_pixels(thumb.data)
    assert len(rows) == 124 * (1 + 220 * 4)
    # The generator draws a teal disc on a dark background (dev/tools/make_sample_gcode.py).
    corner = rows[1:5]
    centre_row = rows[62 * (1 + 880) : 63 * (1 + 880)]
    centre = centre_row[1 + 110 * 4 : 1 + 111 * 4]
    assert corner == bytes((24, 26, 31, 255))
    assert centre[1] > 150 and centre[2] > 150 and centre[0] < 60


def count_fed_lines(monkeypatch) -> list[int]:
    lines: list[int] = []
    original = ThumbnailScanner.feed

    def counting(self, line):
        lines.append(1)
        return original(self, line)

    monkeypatch.setattr(ThumbnailScanner, "feed", counting)
    return lines


@needs_samples
def test_big_file_is_scanned_up_to_the_first_command(monkeypatch):
    lines = count_fed_lines(monkeypatch)
    assert extract_from_file(SAMPLES / "3dbenchy_prusaslicer.gcode") is not None
    assert len(lines) < 1000  # 3.4 MB file, thumbnail header of ~400 lines


def test_file_without_thumbnail_is_scanned_quickly(monkeypatch, tmp_path):
    gcode = tmp_path / "plain.gcode"
    header = "; generated by PrusaSlicer 2.9.6\n;\n; perimeters extrusion width = 0.45mm\n\n"
    gcode.write_text(header + "G1 X10 Y10 E0.5\n" * 50_000, encoding="utf-8")
    lines = count_fed_lines(monkeypatch)
    assert extract_from_file(gcode) is None
    assert len(lines) < 10


def test_qoi_decoder_handles_every_opcode():
    # 1x5: RGB, index hit, diff, luma, run of 2 (hand-encoded).
    data = (
        b"qoif"
        + struct.pack(">II", 5, 1)
        + bytes([4, 0])
        + bytes([0xFE, 100, 150, 200])  # RGB
        + bytes([0x40 | (3 << 4) | (2 << 2) | 1])  # DIFF +1, 0, -1
        + bytes([0x80 | (32 + 10), (8 + 2) << 4 | (8 - 3)])  # LUMA dg=10, dr-dg=2, db-dg=-3
        + bytes([0xC0 | 1])  # RUN 2
        + b"\x00" * 7
        + b"\x01"
    )
    width, height, rgba = decode_qoi(data)
    assert (width, height) == (5, 1)
    pixels = [tuple(rgba[i : i + 4]) for i in range(0, len(rgba), 4)]
    assert pixels == [
        (100, 150, 200, 255),
        (101, 150, 199, 255),
        (113, 160, 206, 255),
        (113, 160, 206, 255),
        (113, 160, 206, 255),
    ]


def test_scanner_rules(tmp_path):
    jpg = b"\xff\xd8\xff\xe0" + b"fake jpeg"
    gcode = tmp_path / "x.gcode"
    gcode.write_text(
        "; generated by test\n\n"
        + block("thumbnail", 16, 16, tiny_png(16, 16))
        + block("thumbnail_JPG", 64, 48, jpg)
        + block("thumbnail", 99, 99, b"not an image")
        + "G28\n"
        + block("thumbnail", 400, 400, tiny_png(400, 400)),
        encoding="utf-8",
    )
    thumb = extract_from_file(gcode)
    # The block after the first command is ignored; invalid images are skipped.
    assert thumb is not None and thumb.mime == "image/jpeg" and thumb.data == jpg


async def test_endpoint_reads_uploads_and_caches(make_client, tmp_path, monkeypatch):
    uploads = tmp_path / "uploads" / "parts"
    uploads.mkdir(parents=True)
    (uploads / "cube.gcode").write_text(block("thumbnail", 8, 8, tiny_png(8, 8)) + "G28\n")
    (uploads / "plain.gcode").write_text("G28\n")
    client = await make_client()

    resp = await client.get("/local/thumbnail", params={"path": "parts/cube.gcode", "v": "1"})
    assert resp.status == 200
    assert resp.content_type == "image/png"
    assert png_size(await resp.read()) == (8, 8)

    def boom(path):
        raise AssertionError("cache miss")

    monkeypatch.setattr(thumbnails, "extract_from_file", boom)
    assert (await client.get("/local/thumbnail", params={"path": "parts/cube.gcode"})).status == 200

    monkeypatch.undo()
    resp = await client.get("/local/thumbnail", params={"path": "parts/plain.gcode"})
    assert resp.status == 404
    assert (await resp.json())["error"] == "no_thumbnail"
    assert list((tmp_path / "data" / "thumbnails").glob("*.none"))


