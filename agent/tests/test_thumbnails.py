def png_size(data: bytes) -> tuple[int, int]:
    assert data.startswith(thumbnails.PNG_MAGIC)
    return struct.unpack(">II", data[16:24])


def png_pixels(data: bytes) -> bytes:
    """Raw scanlines (filter byte + RGBA) of a PNG written by encode_png."""
    idat = data.index(b"IDAT")
    length = struct.unpack(">I", data[idat - 4 : idat])[0]
    return zlib.decompress(data[idat + 4 : idat + 4 + length])


def block(tag: str, width: int, height: int, data: bytes) -> str:
    b64 = base64.b64encode(data).decode()
    lines = [f"; {tag} begin {width}x{height} {len(b64)}"]
    lines += [f"; {b64[i : i + 78]}" for i in range(0, len(b64), 78)]
    return "\n".join([*lines, f"; {tag} end", ""])


def tiny_png(width: int, height: int) -> bytes:
    return encode_png(width, height, bytes([10, 20, 30, 255]) * width * height)


